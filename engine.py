    ("Дозвонились", "Дозвон всего", lambda d: d["корзина"] in ("Дозвон", "Обещал")),  # M,N
    ("Обещали", "Обещали", lambda d: d["колонка"] == "Обещали"),                     # O,P
    ("Ishlanmagan", "Ishlanmagan", lambda d: d["колонка"] in НЕ_ТРОНУТЫ),            # Q,R
    ("Ko'tarmadi", "Ko'tarmadi", lambda d: d["колонка"] == "Ko'tarmadi"),            # S,T
    ("Объезд", "Объезд", lambda d: d["корзина"] == "Объезд"),                        # U,V
    ("Оплатили", "Оплатили", lambda d: d["оплата_вид"] == "контакт"),                # W..Z
    ("Оплатили без разговора", "Опл. без разг.", lambda d: d["оплата_вид"] == "молча"),
