def _ч(v):
    return repr(round(float(v), 2))


_РЕФ = re.compile(r"^([A-Z]+)(\d+)$")


def _записать(xml, ref, значение):
    """Подменяет в ячейке только значение: стиль, а с ним формат и заливка,
    остаётся шаблонным. Со своим стилем дата показывалась процентами."""
    шаблон = re.compile(r'<c r="%s"([^>]*?)(?:/>|>.*?</c>)' % ref, re.S)
    m = шаблон.search(xml)
    if not m:
        return _вставить_ячейку(xml, ref, '<c r="%s" t="n"><v>%s</v></c>' % (ref, значение))
    атрибуты = re.sub(r'\s+t="[^"]*"', "", m.group(1))   # была строка или формула — станет число
    return "%s<c r=\"%s\"%s t=\"n\"><v>%s</v></c>%s" % (
        xml[:m.start()], ref, атрибуты, значение, xml[m.end():])


def _записать_текст(xml, ref, текст, стиль):
    """Текст своим стилем — для колонок-кнопок, которых в шаблоне нет вовсе."""
    новая = ('<c r="%s" s="%d" t="inlineStr"><is><t xml:space="preserve">%s</t></is></c>'
             % (ref, стиль, _экран(текст)))
    шаблон = re.compile(r'<c r="%s"[^>]*?(?:/>|>.*?</c>)' % ref, re.S)
    m = шаблон.search(xml)
    if m:
        return xml[:m.start()] + новая + xml[m.end():]
    return _вставить_ячейку(xml, ref, новая)


def _вставить_ячейку(xml, ref, готовая):
    """Пустых ячеек в шаблоне может не быть вовсе — добавляем на своё место по порядку."""
    буквы, номер = _РЕФ.match(ref).groups()
    строка = re.search(r'<row r="%s"[^>]*>(.*?)</row>' % номер, xml, re.S)
    if not строка:
        raise RuntimeError("нет строки %s" % номер)
    мой = openpyxl.utils.column_index_from_string(буквы)
    for c in re.finditer(r'<c r="([A-Z]+)%s"' % номер, строка.group(1)):
        if openpyxl.utils.column_index_from_string(c.group(1)) > мой:
            место = строка.start(1) + c.start()
            return xml[:место] + готовая + xml[место:]
    return xml[:строка.end(1)] + готовая + xml[строка.end(1):]


def _флаги_стилей(данные_styles: bytes) -> bytes:
    """Excel игнорирует формат и заливку, если нет явных apply-флагов."""
    XF = re.compile(r'<xf\b[^>]*?/>|<xf\b[^>]*?>.*?</xf>', re.S)
    st = данные_styles.decode("utf-8")
    блок = re.search(r'(<cellXfs count="\d+">)(.*?)(</cellXfs>)', st, re.S)
    if not блок:
        return данные_styles

    def один(xf):
        г = xf[:xf.index('>') + 1]
        х = xf[len(г):]
        def атр(и):
            m = re.search(r'\b%s="([^"]*)"' % и, г)
            return m.group(1) if m else None
        доб = []
        for флаг, ключ, пусто in (("applyNumberFormat", "numFmtId", ("0", None)),
                                  ("applyFill", "fillId", ("0", "1", None)),
                                  ("applyFont", "fontId", ("0", None)),
                                  ("applyBorder", "borderId", ("0", None))):
            if атр(флаг) is None and атр(ключ) not in пусто:
                доб.append('%s="1"' % флаг)
        if атр("applyAlignment") is None and "<alignment" in х:
            доб.append('applyAlignment="1"')
        if not доб:
            return xf
        вст = " " + " ".join(доб)
        return (г[:-2] + вст + "/>" if г.endswith("/>") else г[:-1] + вст + ">") + х

    новый = st[:блок.start(2)] + "".join(один(x) for x in XF.findall(блок.group(2))) + st[блок.end(2):]
    return новый.encode("utf-8")


