# ---------------------------------------------------------------- утилиты

def норм(v) -> str:
    return (str(v).strip().lower()
            .replace("’", "'").replace("`", "'").replace("‘", "'").replace("ʻ", "'"))


def _листы(путь):
    wb = openpyxl.load_workbook(путь, data_only=True, read_only=True)
    try:
        return [[list(r) for r in wb[имя].iter_rows(values_only=True)] for имя in wb.sheetnames]
    finally:
        wb.close()


def _шапка(строки, обязательные):
    for i, r in enumerate(строки):
        if not r:
            continue
        ячейки = {str(c).strip() for c in r if c is not None}
        if all(о in ячейки for о in обязательные):
            return i, [str(c).strip().replace("\n", " ") if c is not None else ""
                       for c in r]
    return None, None


# ---------------------------------------------------------------- суммы из текста

_ЕДИНИЦЫ = {"mln": 1_000_000, "млн": 1_000_000, "million": 1_000_000, "mln.": 1_000_000,
            "ming": 1_000, "минг": 1_000, "tys": 1_000, "тыс": 1_000}
_С_ЕДИНИЦЕЙ = re.compile(r'(\d+(?:[.,]\d+)?)\s*(mln\.?|млн|million|ming|минг|tys|тыс)\b', re.I)
_ЧИСЛО = re.compile(r'(?<![\d\-])(\d{1,3}(?:[  .,]\d{3})+|\d{5,9})(?![\d\-])')
_ТЕЛЕФОН = re.compile(r'(?:\+?998|tel|nomer|raqam|telefon)\D{0,3}\d', re.I)


_ЗНАКИ = re.compile(r"[\s\-–—_,;:.()\[\]/]+")


def _без_кому(t) -> str:
    """«to'ladi - filialga» -> «to'ladi»: убираем уточнение и знаки вокруг него."""
    for слово in КОМУ_НАМ + КОМУ_ФИЛИАЛУ:
        t = t.replace(слово, " ")
    return _ЗНАКИ.sub(" ", t).strip()


def кому_из_текста(текст) -> str:
    """«To'ladi - filialga» -> «филиалу», «To'ladi (bizga)» -> «нам»."""
    t = норм(текст)
    if any(s in t for s in КОМУ_НАМ):
        return "нам"
    if any(s in t for s in КОМУ_ФИЛИАЛУ):
        return "филиалу"
    return ""


def исход_из_текста(текст) -> str:
    """Чем кончился объезд: «Uyiga borildi - to'ladi» -> «оплатил»,
    «Uyiga borildi - va'da berdi» -> «обещал»."""
    t = норм(текст)
    if any(s in t for s in ОПЛАЧЕНО):
        return "оплатил"
    if any(s in t for s in ОБЕЩАЛ):
        return "обещал"
    return ""


def статус_из_текста(текст) -> str:
    """Корзина отчёта по тексту: сперва точный список, потом вольные пометки."""
    t = норм(текст)
    if not t:
        return ""
    if t in ИЗ_СПИСКА:
        return ИЗ_СПИСКА[t]
    основа = _без_кому(t)           # статус с приставкой «filialga/bizga»
    if основа in ИЗ_СПИСКА:
        return ИЗ_СПИСКА[основа]
    if any(s in t for s in ОБЪЕЗД):
        return "Объезд"
    if any(s in t for s in ОПЛАЧЕНО):
        return "Оплачено"
    if any(s in t for s in ОБЕЩАЛ):
        return "Обещал"
    if any(s in t for s in ДОЗВОН):
        return "Дозвон"
    if any(s in t for s in НЕДОЗВОН):
        return "Недозвон"
    return ""


