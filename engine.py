def определить_тип(путь) -> str | None:
    """'просрочка' — выгрузка по просроченным, 'кредиты' — активные кредиты."""
    try:
        листы = _листы(путь)
    except Exception:
        return None
    for строки in листы:
        if _шапка(строки, ("Итого просрочка",))[0] is not None:
            return "просрочка"
        if _шапка(строки, ("Филиал", "Общая задолженность"))[0] is not None:
            return "кредиты"
    return None


def _рабочий_лист(путь, обязательные):
    for строки in _листы(путь):
        i, hdr = _шапка(строки, обязательные)
        if i is not None:
            данные = [r for r in строки[i + 1:] if r and any(c is not None for c in r)]
            return hdr, данные
    raise ОшибкаФайла("Faylda kerakli jadvalni topmadim («%s» ustuni)."
                      % "», «".join(обязательные))


БЕЗ_КОДА = "?"                  # временный ключ строки с испорченным кодом: «?номер»


def _код_испорчен(код) -> bool:
    """Ни буквы, ни цифры — «`», пробел, «-»: код стёрли или задели при правке."""
    return not any(ch.isalnum() for ch in str(код))


def читать_просрочку(путь, колонка_статуса="E", колонка_комментария="F"):
    """
    Возвращает {код кредита: {...}} и служебные сведения о файле.
    Статус берём из заданной колонки; если там пусто — ищем по содержимому.
    """
    hdr, данные = _рабочий_лист(путь, ("Итого просрочка",))
    к = {h: i for i, h in enumerate(hdr)}
    if "Код клиента" not in к:
        raise ОшибкаФайла("Faylda «Код клиента» ustuni yo'q — qatorlarni shu bo'yicha bog'layman.")

    iK = к["Код клиента"]
    iO = к.get("Область")
    iF = к.get("Филиал")
    iS = к["Итого просрочка"]
    ширина = max((len(r) for r in данные), default=len(hdr))
    # ФИО, телефон, адрес — для списка недозвона; по названию, без учёта регистра
    iКарточка = {h.lower().strip(): j for j, h in enumerate(hdr)
                 if h.lower().strip() in БАЗОВЫЕ_КОЛОНКИ}

    def бук(б):
        return openpyxl.utils.column_index_from_string(б) - 1

    jСтатус = бук(колонка_статуса)
    jКоммент = бук(колонка_комментария)

    def базовая(j):
        return (hdr[j].lower().strip() if j < len(hdr) else "") in БАЗОВЫЕ_КОЛОНКИ

    # если в заданной колонке нет ни одного знакомого статуса — ищем сами
    знакомых = sum(1 for r in данные            # с приставками тоже считаются
                   if len(r) > jСтатус and статус_из_текста(r[jСтатус]))
    if знакомых == 0:
        лучший, лучшее = None, 0
        for j in range(ширина):
            if базовая(j):
                continue
            счёт = sum(1 for r in данные
                       if len(r) > j and статус_из_текста(r[j]))
            if счёт > лучшее:
                лучший, лучшее = j, счёт
        if лучший is not None:
            jСтатус = лучший
            # комментарий — соседняя колонка, но только если она не служебная,
            # иначе «Область» или «Телефон» сойдут за пометку в каждой строке
            jКоммент = (лучший + 1 if лучший + 1 < ширина and not базовая(лучший + 1)
                        else -1)

    # то же и для колонок, заданных вручную
    if jКоммент >= 0 and базовая(jКоммент):
        jКоммент = -1

    # все прочие колонки — тоже пометки (старые файлы пишут куда попало)
    прочие = [j for j in range(ширина)
              if (hdr[j].lower().strip() if j < len(hdr) else "") not in БАЗОВЫЕ_КОЛОНКИ
              and j not in (jСтатус, jКоммент)]  # -1 сюда не попадёт

    строки = {}
    заполнено = 0
    без_кода = []                          # ФИО строк, где код испорчен
    for номер, r in enumerate(данные):
        if len(r) <= iK or r[iK] in (None, ""):
            continue                       # последняя строка «Итого» — без кода
        код = str(r[iK]).strip()
        бери = lambda j: (r[j] if 0 <= j < len(r) else None)
        if _код_испорчен(код):
            # «`» или пробел вместо «Кр-…»: без своего ключа строка стала бы
            # отдельным клиентом. Настоящий код свод найдёт по ФИО в других файлах
            клиент = бери(iКарточка["клиент"]) if "клиент" in iКарточка else None
            if клиент in (None, "") or "итого" in str(клиент).lower():
                continue
            код = "%s%d" % (БЕЗ_КОДА, номер)
            без_кода.append(" ".join(str(клиент).split()))
        статус_ячейка = бери(jСтатус)
        коммент = бери(jКоммент)
        пометки = [str(бери(j)).strip() for j in прочие if бери(j) not in (None, "")]

        # статус берём только из своей колонки: комментарий и прочие колонки
        # больше не считаются пометкой — иначе забытый статус выглядел как «не понял»
        статус = статус_из_текста(статус_ячейка)
        кому = кому_из_текста(статус_ячейка)
        # чем кончился объезд — только по самому статусу («Uyiga borildi - to'ladi»
        # в старых файлах). В комментарий не смотрим: работаем со статусами
        исход = исход_из_текста(статус_ячейка) if статус == "Объезд" else ""

        просрочка = (float(r[iS] or 0)
                     if len(r) > iS and isinstance(r[iS], (int, float)) else 0.0)

        сумма_оплаты = 0.0
        по_просрочке = False
        if статус == "Оплачено" or исход == "оплатил":
            # работаем только со статусом: отметили «To'ladi» — значит клиент
            # закрыл свою просрочку, её и считаем оплатой. Комментарий не читаем;
            # точную сумму бот всё равно перепроверит завтра разницей выгрузок
            сумма_оплаты = просрочка
            по_просрочке = просрочка > 0

        # работой считаем только выбранный статус. Один комментарий работой не
        # считается: иначе строка с одной суммой выглядела бы как «статус не понят»
        есть_пометка = статус_ячейка not in (None, "")
        забыли_статус = not есть_пометка and коммент not in (None, "")
        if есть_пометка:
            заполнено += 1

        строки[код] = {
            "область": (str(r[iO]).strip().upper() if iO is not None and len(r) > iO and r[iO] else ""),
            "филиал": (str(r[iF]).strip() if iF is not None and len(r) > iF and r[iF] else ""),
            "просрочка": просрочка,
            "статус": статус,
            "кому": кому,
            "исход": исход,
            "оплата": сумма_оплаты,
            "оплата_по_просрочке": по_просрочке,
            "текст": " | ".join(x for x in
                                ([str(статус_ячейка).strip()] if статус_ячейка not in (None, "") else []) +
                                ([str(коммент).strip()] if коммент not in (None, "") else []) +
                                пометки),
            "есть_пометка": есть_пометка,
            "забыли_статус": забыли_статус,
            "карточка": {h: бери(j) for h, j in iКарточка.items()},
        }

    if not строки:
        raise ОшибкаФайла("Faylda kredit kodi bo'lgan birorta qator topilmadi.")

    сведения = {
        "строк": len(строки),
        "заполнено": заполнено,
        "колонка_статуса": openpyxl.utils.get_column_letter(jСтатус + 1),
        "колонка_комментария": (openpyxl.utils.get_column_letter(jКоммент + 1)
                                if jКоммент >= 0 else "—"),
        "области": sorted({d["область"] for d in строки.values()
                           if d["есть_пометка"] and d["область"]}),
        "без_кода": без_кода,
    }
    return строки, сведения


def читать_кредиты(путь):
    """{область: сумма портфеля}, {область: кол-во}"""
    hdr, данные = _рабочий_лист(путь, ("Филиал", "Общая задолженность"))
    к = {h: i for i, h in enumerate(hdr)}
    iO, iS = к.get("Область"), к["Общая задолженность"]
    iD = к.get("Номер договора")
    if iO is None:
        raise ОшибкаФайла("Kreditlar faylida «Область» ustuni yo'q — "
                          "usiz portfelni viloyatlar bo'yicha hisoblab bo'lmaydi.")
    сумма, штук = defaultdict(float), defaultdict(int)
    for r in данные:
        if len(r) <= iS:
            continue
        if iD is not None and (len(r) <= iD or r[iD] in (None, "")):
            continue
        о = str(r[iO]).strip().upper() if len(r) > iO and r[iO] else ""
        if not о:
            continue
        сумма[о] += float(r[iS] or 0) if isinstance(r[iS], (int, float)) else 0.0
        штук[о] += 1
    if not сумма:
        raise ОшибкаФайла("Kreditlar faylida viloyati ko'rsatilgan qatorlar topilmadi.")
    return dict(сумма), dict(штук)


