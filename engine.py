def _кратко(область):
    return КОРОТКО.get(область, область.title())


def штук(v):
    """2720 -> «2 720»: длинные числа читаются глазом, а не пересчитываются."""
    return "{:,}".format(int(v)).replace(",", " ")


def молчуны(итог):
    """Области, где кредиты есть, а работы за день не видно."""
    return [о for о in ОБЛАСТИ
            if sum(итог["свод"][о][к][1] for к in КОРЗИНЫ) > 0
            and not any(итог["свод"][о][к][1] for к in ("Дозвон", "Обещал", "Объезд"))
            and итог["оплаты"][о][1] == 0]


def текст_сводки(итог, портфель_сумма, портфель_штук=None, заметки=()):
    """Одно сообщение целиком: цифры, работа за день, служебные заметки."""
    млрд = lambda v: "%.2f mlrd" % (v / 1_000_000_000)
    млн = lambda v: "%.1f mln" % (v / 1_000_000)
    штк = штук

    просроч = sum(sum(d[к][0] for к in КОРЗИНЫ) for d in итог["свод"].values())
    кредитов = sum(sum(d[к][1] for к in КОРЗИНЫ) for d in итог["свод"].values())
    опл_с = sum(v[0] for v in итог["оплаты"].values())
    опл_ш = sum(v[1] for v in итог["оплаты"].values())
    порт = sum(портфель_сумма.values())
    порт_шт = sum((портфель_штук or {}).values())

    # разбивка — те же колонки, что в таблице, поэтому строки складываются в итог
    счёт = defaultdict(int)
    for d in итог["объединение"].values():
        if d.get("колонка"):
            счёт[d["колонка"]] += 1
    не_тронуто = sum(счёт[к] for к in НЕ_ТРОНУТЫ)

    ш = ["📊 MUDDATI O'TGAN QARZLAR", datetime.now().strftime("%d.%m.%Y"), ""]
    ш.append("💼 Portfel: %s so'm%s"
             % (млрд(порт), " · %s kredit" % штк(порт_шт) if порт_шт else ""))
    ш.append("🔴 Muddati o'tgan: %s so'm · %s kredit (%.1f%%)"
             % (млрд(просроч), штк(кредитов), (просроч / порт * 100) if порт else 0))
    ш.append("")
    ш.append("🛠 Ishlangan: %s / %s kredit" % (штк(итог["обработано"]), штк(кредитов)))
    for значок, колонки, подпись_ in (("📞", ("Ko'tardi",), "Ko'tardi"),
                                      ("🤝", ("Обещали",), "Va'da berdi"),
                                      ("✅", ("Оплатил дозвон",), "To'ladi"),
                                      ("🚗", ("Объезд", "Объезд оплатил"), "Uyiga borildi"),
                                      ("📵", ("Ko'tarmadi",), "Ko'tarmadi")):
        сколько = sum(счёт[к] for к in колонки)
        if сколько:
            ш.append("   %s %-14s %s" % (значок, подпись_, штк(сколько)))
    ш.append("⏳ Ishlanmagan: %s kredit" % штк(не_тронуто))
    ш.append("")
    ш.append("💰 Jami to'lov: %s kredit → %s so'm" % (штк(опл_ш), млн(опл_с)))
    if итог["оплата_по_разнице"]:
        ш.append("      (kechagi yuklama bilan farqi bo'yicha)")
    молча = sum(v[1] for v in итог.get("оплаты_молча", {}).values())
    if молча:
        ш.append("      (%s tasi aloqasiz to'ladi)" % штк(молча))
    if итог.get("оплат_по_просрочке"):
        ш.append("      (summa qarz bo'yicha olindi — ertaga yuklamalar farqi bilan aniqlanadi)")

    хвост = []
    молчат = молчуны(итог)
    if молчат:
        сумма_молчат = sum(sum(итог["свод"][о][к][0] for к in КОРЗИНЫ) for о in молчат)
        хвост.append("⚠️ Hisobot bermadi (%d): %s — %s so'm"
                     % (len(молчат), ", ".join(_кратко(о) for о in молчат),
                        млрд(сумма_молчат)))
    # код клиента стёрт («`», пробел): без починки такой клиент считался дважды
    файл_ = lambda имя: re.sub(r"^\d+_", "", os.path.basename(имя))
    for ключ, начало in (("код_починен", "🔧 Mijoz kodi buzilgan — ism bo'yicha tiklandi"),
                         ("код_не_найден", "⚠️ Mijoz kodi buzilgan, topilmadi — alohida")):
        случаи = итог.get(ключ) or []
        if случаи:
            хвост.append("%s: %s%s" % (начало, "; ".join(
                "%s («%s»)" % (" ".join(str(с[1]).split()[:2]), файл_(с[0])) for с in случаи[:3]),
                " +%d" % (len(случаи) - 3) if len(случаи) > 3 else ""))
    if итог["без_статуса"]:
        хвост.append("❓ Holat o'qilmadi: %s qator — Ishlanmagan ichida"
                     % штк(итог["без_статуса"]))
        частые = sorted(итог.get("непонятные", {}).items(), key=lambda п: -п[1])[:3]
        if частые:      # видно, какие формулировки чинить, не открывая файлы
            хвост.append("   " + " · ".join("«%s» %d" % (т[:22], n) for т, n in частые))
    if итог.get("забыли_статус"):
        хвост.append("✍️ Holat tanlanmagan, izoh bor: %s qator — Ishlanmagan ichida"
                     % штк(итог["забыли_статус"]))
    if итог["прочие_области"]:
        хвост.append("❓ Notanish viloyat: %s" % ", ".join(итог["прочие_области"]))
    хвост.extend(заметки)

    # подпись ограничена — при переполнении жертвуем служебными строками с конца
    while хвост:
        текст = "\n".join(ш + [""] + хвост)
        if len(текст) <= ПОДПИСЬ_МАКС:
            return текст
        хвост.pop()
    return "\n".join(ш)[:ПОДПИСЬ_МАКС]
